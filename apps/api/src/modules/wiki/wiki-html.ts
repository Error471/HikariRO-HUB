import sanitizeHtml from 'sanitize-html';

/** Solo valores CSS sin url(), expression() ni javascript:. */
const SAFE_CSS = /^(?!.*(?:url\s*\(|expression\s*\(|javascript:|@import|\\))[-#%.,()/\w\s"'!+*]*$/i;

const allowedCssProperties = [
  'color',
  'background',
  'background-color',
  'background-image',
  'border',
  'border-top',
  'border-right',
  'border-bottom',
  'border-left',
  'border-color',
  'border-style',
  'border-width',
  'border-radius',
  'border-collapse',
  'border-spacing',
  'padding',
  'padding-top',
  'padding-right',
  'padding-bottom',
  'padding-left',
  'margin',
  'margin-top',
  'margin-right',
  'margin-bottom',
  'margin-left',
  'text-align',
  'vertical-align',
  'font-size',
  'font-weight',
  'font-style',
  'font-family',
  'line-height',
  'letter-spacing',
  'text-decoration',
  'text-transform',
  'white-space',
  'width',
  'max-width',
  'min-width',
  'height',
  'max-height',
  'min-height',
  'display',
  'float',
  'clear',
  'box-shadow',
  'opacity',
  'gap',
  'flex',
  'flex-wrap',
  'flex-direction',
  'justify-content',
  'align-items',
  'grid-template-columns',
  'list-style',
  'list-style-type',
  'overflow',
  'overflow-x',
  'table-layout',
  'word-break',
];

const allowedStyles = Object.fromEntries(
  allowedCssProperties.map((property) => [property, [SAFE_CSS]]),
);

/**
 * Lista blanca de clases: solo las de MediaWiki, la wiki de HikariRO y la copia local (`wk-*`), para que el contenido
 * no pueda activar utilidades de la app (p. ej. `fixed` o `hidden` de Tailwind).
 */
const allowedClasses = [
  'wk-*',
  'tw',
  'mw-*',
  'hro-*',
  'hro2-*',
  'wikitable',
  'sortable',
  'image',
  'center',
  'floatleft',
  'floatright',
  'floatnone',
  'thumb',
  'thumbinner',
  'thumbimage',
  'thumbcaption',
  'tright',
  'tleft',
  'tnone',
  'magnify',
  'collapsible',
  'external',
  'text',
  'gallery',
  'gallerybox',
  'gallerytext',
  'reference',
  'references',
  'noprint',
  'plainlinks',
  'toc',
  'tocnumber',
  'toctext',
];

export function sanitizeWikiHtml(html: string): string {
  return sanitizeHtml(html, {
    allowedTags: [
      'h1',
      'h2',
      'h3',
      'h4',
      'h5',
      'h6',
      'p',
      'div',
      'span',
      'a',
      'b',
      'i',
      'strong',
      'em',
      'u',
      's',
      'del',
      'ins',
      'sup',
      'sub',
      'br',
      'hr',
      'ul',
      'ol',
      'li',
      'dl',
      'dt',
      'dd',
      'table',
      'thead',
      'tbody',
      'tfoot',
      'tr',
      'th',
      'td',
      'caption',
      'colgroup',
      'col',
      'img',
      'figure',
      'figcaption',
      'blockquote',
      'pre',
      'code',
      'kbd',
      'small',
      'big',
      'center',
      'abbr',
      'mark',
      'details',
      'summary',
      // Iconos en línea de la portada (sin <use>, <image> ni scripts).
      'svg',
      'g',
      'path',
      'circle',
      'ellipse',
      'rect',
      'line',
      'polygon',
      'polyline',
    ],
    allowedAttributes: {
      '*': ['class', 'id', 'style', 'title', 'lang', 'dir'],
      a: ['href', 'target', 'rel', 'data-wiki'],
      img: ['src', 'srcset', 'alt', 'width', 'height', 'loading', 'decoding'],
      td: ['colspan', 'rowspan', 'align', 'valign'],
      th: ['colspan', 'rowspan', 'scope', 'align', 'valign'],
      col: ['span'],
      ol: ['start', 'type'],
      // El analizador pasa los atributos a minúsculas; el navegador restaura `viewBox` al leer HTML.
      svg: ['viewbox', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'aria-hidden'],
      g: ['fill', 'stroke', 'stroke-width'],
      path: ['d'],
      circle: ['cx', 'cy', 'r'],
      ellipse: ['cx', 'cy', 'rx', 'ry'],
      rect: ['x', 'y', 'width', 'height', 'rx'],
      line: ['x1', 'y1', 'x2', 'y2'],
      polygon: ['points'],
      polyline: ['points'],
    },
    allowedClasses: { '*': allowedClasses },
    allowedStyles: { '*': allowedStyles },
    allowedSchemes: ['http', 'https', 'mailto'],
    allowedSchemesAppliedToAttributes: ['href', 'src'],
    allowProtocolRelative: false,
    transformTags: {
      a: (tagName, attribs) => {
        if (attribs.target === '_blank') attribs.rel = 'noopener noreferrer nofollow';
        return { tagName, attribs };
      },
    },
  });
}
